# 「省直辖县级行政区划」这种伪地级：名字不能直接摆给用户看，把它下面那些县市
# **拆到省级那一层**（河南省 → 济源市），行里也就不会冒出这么一长串。
DIRECT_COUNTY_KEY = "直辖县级行政区划"


def build_china(pca: list[dict]) -> dict[str, dict[str, tuple[str, ...]]]:
    """省 → 市 → 区。直辖市并掉「市辖区」那一层、伪地级拆开（见文件头说明）。"""
    china: dict[str, dict[str, tuple[str, ...]]] = {}
    for province in pca:
        city_map: dict[str, tuple[str, ...]] = {}
        for city in province.get("children") or []:
            districts = tuple(
                item["name"] for item in (city.get("children") or [])
            )
            if DIRECT_COUNTY_KEY in city["name"]:
                # 伪地级：下面的每个县市各自成为省级下面的一行（叶子）。
                city_map.update({name: () for name in districts})
            elif province["name"] in MUNICIPALITIES:
                # 直辖市：把各区县直接挂在省名下面（本来还会多一层「市辖区 / 县」）。
                merged = city_map.get(province["name"], ())
                city_map[province["name"]] = merged + districts
            else:
                city_map[city["name"]] = districts
        china[province["name"]] = city_map
    china.update(CHINA_EXTRA)
    return china


def _render_countries(countries: list[str]) -> str:
    lines = ["COUNTRIES: tuple[str, ...] = ("]
    lines += [f'    "{name}",' for name in countries]
    lines.append(")")
    return "\n".join(lines)


def _render_china(china: dict[str, dict[str, tuple[str, ...]]]) -> str:
    lines = ["CHINA: dict[str, dict[str, tuple[str, ...]]] = {"]
    for province, cities in china.items():
        lines.append(f'    "{province}": {{')
        for city, districts in cities.items():
            if not districts:
                # 叶子（如省直辖的「济源市」）：空元组写 `()` —— `(,)` 不是合法 Python。
                lines.append(f'        "{city}": (),')
                continue
            items = ", ".join(f'"{name}"' for name in districts)
            lines.append(f'        "{city}": ({items},),')
        lines.append("    },")
    lines.append("}")
    return "\n".join(lines)


def _render_world(world: dict[str, tuple[str, ...]]) -> str:
    lines = ["WORLD: dict[str, tuple[str, ...]] = {"]
    for country, regions in world.items():
        items = ", ".join(f'"{name}"' for name in regions)
        if len(f'    "{country}": ({items},),') <= 88:
            lines.append(f'    "{country}": ({items},),')
            continue
        lines.append(f'    "{country}": (')
        row: list[str] = []
        for name in regions:
            cell = f'"{name}",'
            if len("            " + " ".join(row + [cell])) > 88:
                lines.append("        " + " ".join(row))
                row = []
            row.append(cell)
        if row:
            lines.append("        " + " ".join(row))
        lines.append("    ),")
    lines.append("}")
    return "\n".join(lines)


